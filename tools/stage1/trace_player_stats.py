#!/usr/bin/env python3
"""Export the original single-player Player stats event subtree.

Run from the repository root:
  python tools/stage1/trace_player_stats.py

Reads only the parsed Construct project generated by extract_construct.py.
It does not scan raw/, romfs/, MP JSON, or the restricted source folder.
"""
import argparse
import csv
import json
from pathlib import Path

TARGET_UID = 7463747062628312
TARGET_NAME = "Player stats"


def event_parts(event):
    if not isinstance(event, list) or not event or event[0] != 0:
        return None
    header = event[1] if len(event) > 1 else None
    name = header[1] if isinstance(header, list) and len(header) > 1 and isinstance(header[1], str) else ""
    uid = event[4] if len(event) > 4 and isinstance(event[4], int) else 0
    conditions = event[5] if len(event) > 5 and isinstance(event[5], list) else []
    actions = event[6] if len(event) > 6 and isinstance(event[6], list) else []
    children = event[7] if len(event) > 7 and isinstance(event[7], list) else []
    return uid, name, conditions, actions, children


def find_group(items):
    """Find the named group at any nesting depth, not just sheet roots."""
    for event in items if isinstance(items, list) else []:
        parts = event_parts(event)
        if parts is None:
            continue
        uid, name, _, _, children = parts
        if uid == TARGET_UID or name == TARGET_NAME:
            return event
        match = find_group(children)
        if match is not None:
            return match
    return None


def walk(items, parent_uid=0, depth=0):
    for event in items if isinstance(items, list) else []:
        parts = event_parts(event)
        if parts is None:
            continue
        uid, name, conditions, actions, children = parts
        yield {
            "uid": uid,
            "parent_uid": parent_uid,
            "depth": depth,
            "group": name,
            "conditions": conditions,
            "actions": actions,
            "child_count": len(children),
        }
        yield from walk(children, uid, depth + 1)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="data/stage1/construct_project_parsed.json")
    parser.add_argument("--out", default="data/stage1/player_stats_trace")
    args = parser.parse_args()

    root = json.loads(Path(args.input).read_text(encoding="utf-8"))
    project = root.get("project")
    if not isinstance(project, list) or len(project) <= 6 or not isinstance(project[6], list):
        raise SystemExit("Input is not a parsed Construct project export")

    group = None
    for sheet in project[6]:
        if not isinstance(sheet, list) or len(sheet) < 2 or sheet[0] != "Game_events":
            continue
        group = find_group(sheet[1])
        break
    if group is None:
        raise SystemExit("Player stats group UID/name not found in Game_events")

    found = list(walk([group]))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    json_path = out / "events.json"
    csv_path = out / "events.csv"
    json_path.write_text(json.dumps(found, ensure_ascii=False, indent=2), encoding="utf-8")
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=[
            "uid", "parent_uid", "depth", "group", "conditions", "actions", "child_count"
        ])
        writer.writeheader()
        for row in found:
            writer.writerow({
                **row,
                "conditions": json.dumps(row["conditions"], ensure_ascii=False),
                "actions": json.dumps(row["actions"], ensure_ascii=False),
            })
    print(f"Wrote {len(found)} source event records to {json_path} and {csv_path}")


if __name__ == "__main__":
    main()

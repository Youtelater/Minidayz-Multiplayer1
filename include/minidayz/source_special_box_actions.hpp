// Consumer owns transaction, RNG, Create defaults, selected-object state,
// and full Spawn_drop behavior. Pass zero through as the original request.
template<class Choose,class Unlocked,class Apply,class Spawn>
bool source_execute_special_box(int category,Choose&& choose,Unlocked&& unlocked,Apply&& apply,Spawn&& spawn) {
    if(category==1022){
        for(const auto& pool:kSourceSpecialBoxPools){
            const std::size_t i=choose(pool.count);
            if(i>=pool.count||!spawn(kSourceSpecialBoxChoices[pool.first+i],pool))return false;
        }
        return true;
    }
    int outcome=0;
    const std::size_t initial=category==1020?6:category==1021?22:0;
    if(initial){
        const std::size_t i=choose(initial);
        if(i>=initial)return false;
        outcome=static_cast<int>(i)+1;
    }
    for(const auto& b:kSourceSpecialBoxBranches){
        if(b.category!=category||b.outcome!=outcome||b.unlock.empty())continue;
        if(!unlocked(b.unlock)){
            const std::size_t i=choose(b.retry_count);
            if(i>=b.retry_count)return false;
            outcome=static_cast<int>(i)+1;
        }
        break;
    }
    for(const auto& b:kSourceSpecialBoxBranches){
        if(b.category!=category||b.outcome!=outcome)continue;
        for(std::size_t i=0;i<b.count;++i)
            if(!apply(kSourceSpecialBoxActions[b.first+i]))return false;
        return true;
    }
    return false;
}
